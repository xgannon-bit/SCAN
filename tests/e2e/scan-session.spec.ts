  await nav(page, 'Board workspace').click();
  await expect(page.getByLabel('Placement to inspect')).toHaveValue('');
  await nav(page, 'Source intake').click();
  await page.getByLabel('CSV delimiter').selectOption(';');
  await expect(page.getByRole('button', { name: 'Validate placements' })).toHaveCount(0);
  await page.getByLabel('CSV delimiter').selectOption(',');
  await read(page); await validate(page);
  await page.getByLabel('Worksheet index').fill('1');
  await expect(page.getByRole('button', { name: 'Validate placements' })).toHaveCount(0);
  await page.getByLabel('Worksheet index').fill('0');
  await read(page); await validate(page);
  await page.getByLabel('Placement file').setInputFiles({ ...file, name: 'other-fictional.csv' });
  await nav(page, 'Job dashboard').click();
  await expect(page.getByRole('status', { name: 'Placement session status' })).toHaveText('Ready to read');
  await page.getByRole('button', { name: 'Clear session', exact: true }).click();
